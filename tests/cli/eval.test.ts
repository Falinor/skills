// The agent eval harness, driven from the outside without any model call:
// the fixture builder through `prepare`, the grader on hand-written tour
// plans, and the harness with a fake agent on PATH.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { afterEach, beforeEach, test } from 'node:test';
import { makeSandbox, type Sandbox } from '../support/sandbox.ts';

const evals = path.join(import.meta.dirname, '../../evals/review-tour');

let sandbox: Sandbox;
beforeEach(() => {
  sandbox = makeSandbox();
});
afterEach(() => sandbox.cleanup());

type File = { path: string; proofs?: string[]; generated?: string };

/** Builds the fixture into the sandbox and captures it with `prepare`, as the agent would. */
function prepareFixture(): { repo: string; folder: string } {
  const repo = path.join(sandbox.root, 'shop');
  const built = spawnSync(process.execPath, [path.join(evals, 'fixture.ts'), repo], { env: sandbox.env, encoding: 'utf8' });
  assert.equal(built.status, 0, built.stderr);
  const prepared = sandbox.run(['prepare', 'feature', '--base', 'trunk'], { cwd: repo });
  assert.equal(prepared.status, 0, prepared.stderr);
  return { repo, folder: path.join(sandbox.tmp, 'review-tour', 'shop-feature') };
}

function filesOf(folder: string): Map<string, File> {
  const change = JSON.parse(fs.readFileSync(path.join(folder, 'change.json'), 'utf8'));
  return new Map(change.files.map((file: File) => [file.path, file]));
}

test('the fixture holds a cross-file move, a rename, a reformat, a generated file, wiring and a hidden behaviour change', () => {
  const { repo, folder } = prepareFixture();

  const files = filesOf(folder);
  assert.deepEqual(
    [...files.keys()].sort(),
    ['src/cart.ts', 'src/discount.ts', 'src/format.ts', 'src/generated/catalog.ts', 'src/index.ts', 'src/money.ts', 'src/text.ts'],
  );
  // A function leaves money.ts and lands in format.ts: a move between files, never a reorder within one.
  assert.deepEqual(files.get('src/money.ts')?.proofs, ['pure-move']);
  assert.deepEqual(files.get('src/format.ts')?.proofs, ['pure-move']);
  assert.deepEqual(files.get('src/text.ts')?.proofs, ['pure-rename']);
  assert.deepEqual(files.get('src/cart.ts')?.proofs, ['whitespace-only']);
  assert.equal(files.get('src/generated/catalog.ts')?.generated, 'base');
  for (const unproven of ['src/index.ts', 'src/discount.ts']) {
    assert.equal(files.get(unproven)?.proofs, undefined, unproven);
    assert.equal(files.get(unproven)?.generated, undefined, unproven);
  }
  // The hidden change: a whole file re-indented, with one line that also changes behaviour.
  const discount = spawnSync('git', ['diff', '--numstat', 'trunk', 'feature', '--', 'src/discount.ts'], { cwd: repo, encoding: 'utf8' });
  const ignoringWhitespace = spawnSync('git', ['diff', '-w', '--numstat', 'trunk', 'feature', '--', 'src/discount.ts'], { cwd: repo, encoding: 'utf8' });
  assert.ok(Number(discount.stdout.split('\t')[0]) >= 10, discount.stdout);
  assert.match(ignoringWhitespace.stdout, /^1\t1\t/);
  assert.match(fs.readFileSync(path.join(folder, 'to-read.patch'), 'utf8'), /^diff --git a\/src\/discount\.ts/m);
});

const intent = {
  why: 'Tidy the shop library before the pricing work.',
  visual: 'src/\n  format.ts  # formatDate, formatPrice\n  text.ts    # was strings.ts',
  mergeDanger: { door: 'two-way', blastRadius: 'checkout: wrong discounts' },
};

const mechanicalStep = {
  title: 'Moves, rename, re-indent and the regenerated catalog',
  tier: 'mechanical',
  files: ['src/money.ts', 'src/format.ts', 'src/text.ts', 'src/cart.ts', 'src/generated/catalog.ts'],
  explanation: 'Proven by git, or declared generated by the base.',
};

/** A tour plan that gets the fixture right. */
const soundPlan = {
  intent,
  steps: [
    {
      title: 'A total equal to a threshold now earns its discount',
      tier: 'core-logic',
      files: ['src/discount.ts'],
      explanation: 'The re-indent hides `>` becoming `>=`.',
      callouts: [{ file: 'src/discount.ts', line: 15, side: 'new', tag: 'Subtle', text: '`>=` now includes the threshold.' }],
    },
    { title: 'Exports follow the moved code', tier: 'wiring', files: ['src/index.ts'], explanation: 'Import paths only.' },
    mechanicalStep,
  ],
};

function writePlan(folder: string, plan: object): void {
  fs.writeFileSync(path.join(folder, 'plan.json'), JSON.stringify(plan, null, 2));
}

/** Writes the plan and renders it, as the agent would; returns render's result. */
function renderPlan(repo: string, folder: string, plan: object) {
  writePlan(folder, plan);
  return sandbox.run(['render', folder], { cwd: repo });
}

function grade(folder: string) {
  return spawnSync(process.execPath, [path.join(evals, 'grade.ts'), folder], { env: sandbox.env, encoding: 'utf8' });
}

test('the grader passes a tour that sets the hidden change in core logic and every proven file in mechanical', () => {
  const { repo, folder } = prepareFixture();
  assert.equal(renderPlan(repo, folder, soundPlan).status, 0);

  const result = grade(folder);

  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.deepEqual(result.stdout.trim().split('\n'), [
    'pass  the hidden change sits in core logic',
    'pass  proven files sit in mechanical',
    'pass  every file appears exactly once',
    'pass  render succeeded and the page exists',
  ]);
});

/** The grader's verdict on one check, by the start of its name. */
function verdict(stdout: string, check: string): string | undefined {
  return stdout.split('\n').find((line) => line.slice(6).startsWith(check));
}

test('the grader fails a tour that flags the hidden change as unproven mechanical', () => {
  const { repo, folder } = prepareFixture();
  const [hidden, wiring] = soundPlan.steps;
  const plan = {
    intent,
    steps: [
      { ...hidden, title: 'Re-indented', callouts: [], unprovenMechanical: ['src/discount.ts'] },
      wiring,
      mechanicalStep,
    ],
  };
  assert.equal(renderPlan(repo, folder, plan).status, 0);

  const result = grade(folder);

  assert.equal(result.status, 1);
  assert.equal(
    verdict(result.stdout, 'the hidden change'),
    'fail  the hidden change sits in core logic: src/discount.ts is flagged unproven mechanical in step 1',
  );
  assert.equal(verdict(result.stdout, 'render'), 'pass  render succeeded and the page exists');
});

test('the grader fails a tour that files the hidden change under wiring', () => {
  const { repo, folder } = prepareFixture();
  const plan = {
    intent,
    steps: [
      { title: 'Re-indent and rewire', tier: 'wiring', files: ['src/discount.ts', 'src/index.ts'], explanation: 'Formatting.' },
      mechanicalStep,
    ],
  };
  assert.equal(renderPlan(repo, folder, plan).status, 0);

  const result = grade(folder);

  assert.equal(result.status, 1);
  assert.equal(
    verdict(result.stdout, 'the hidden change'),
    'fail  the hidden change sits in core logic: src/discount.ts is in wiring step 1',
  );
});
